import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import path from 'node:path'

const read = filename => readFileSync(path.join(process.cwd(), filename), 'utf8')
const app = read('src/App.vue')
const workspace = read('src/components/workspace/WorkspaceDashboard.vue')
const main = read('src/main.ts')
const ui = read('src/stores/ui.ts')
const css = read('src/styles/desktop-resize.css')
const native = read('../desktop/src-tauri/src/main.rs')
const nativeResize = read('../desktop/src-tauri/src/native_main_resize_windows.rs')
const config = JSON.parse(read('../desktop/src-tauri/tauri.conf.json'))

const mainWindow = config.app.windows.find(window => window.label === 'main')
const petWindow = config.app.windows.find(window => window.label === 'pet')
const canvasWindow = config.app.windows.find(window => window.label === 'canvas')
assert.equal(mainWindow.transparent, false)
assert.equal(mainWindow.shadow, false)
assert.equal(mainWindow.decorations, true)
assert.equal(petWindow.decorations, false)
assert.equal(canvasWindow.decorations, false)
// Create the main window decorated so Tauri never attaches its GDI resize child.
assert.equal(petWindow.transparent, true)
assert.equal(canvasWindow.transparent, true)

assert.match(main, /import '\.\/styles\/desktop-resize\.css'/)
assert.doesNotMatch(app, /handleDesktopLiveResize|resizeIdleTimer|desktop-live-resize/)
assert.doesNotMatch(app, /window\.addEventListener\('resize'/)
assert.match(app, /desktop-main-window/)
assert.match(app, /!isPetWindow\.value && !isCanvasWindow\.value/)

assert.match(css, /html\.desktop-main-window body/)
assert.match(css, /html\.desktop-main-window #app/)
assert.match(css, /var\(--bg-primary, #f4f7fb\)/)
assert.match(css, /html\.desktop-main-window \.bg-layer::after/)
assert.match(css, /box-shadow: none/)
assert.match(css, /filter: none/)
assert.match(css, /animation: none/)
assert.match(css, /html\.desktop-main-window \.workspace-dashboard \.panel/)
assert.match(css, /backdrop-filter: none/)
assert.doesNotMatch(css, /desktop-live-resize|blur\(58px\)|58vw/)
assert.match(workspace, /justify-content:space-between;flex-wrap:wrap/)
assert.match(workspace, /\.hero-actions\{display:flex;flex-wrap:wrap/)
assert.doesNotMatch(workspace, /@media\(max-width:1040px\)\{\.dashboard-hero/)
assert.doesNotMatch(css, /^html,\s*body,\s*#app/m)

assert.match(ui, /set_main_window_background_color/)
assert.match(ui, /color: canvas/)
assert.match(ui, /!location\.hash\.startsWith\('#\/pet'\)/)
assert.match(native, /fn set_main_window_background_color/)
assert.match(native, /value\.len\(\) == 6/)
assert.match(native, /set_background_color\(Some\(background\)\)/)
assert.match(native, /Color\(244, 247, 251, 255\)/)
assert.match(native, /native_main_resize_windows::install\(&main\)/)
assert.match(nativeResize, /WS_CAPTION/)
assert.match(nativeResize, /WS_THICKFRAME/)
assert.match(nativeResize, /SWP_FRAMECHANGED/)
assert.match(nativeResize, /SetWindowLongPtrW/)
assert.match(nativeResize, /captionless_style_preserves_native_resize/)
assert.match(nativeResize, /SetWindowSubclass/)
assert.match(nativeResize, /RemoveWindowSubclass/)
assert.match(nativeResize, /DefSubclassProc/)
assert.match(nativeResize, /WM_NCCALCSIZE/)
assert.match(nativeResize, /WM_NCHITTEST/)
assert.match(nativeResize, /GetSystemMetricsForDpi/)
assert.match(nativeResize, /IsZoomed\(hwnd\)/)
assert.match(nativeResize, /border_hit_zones_cover_right_bottom_and_corners_without_content/)
assert.match(nativeResize, /screen_point_preserves_negative_monitor_coordinates/)
assert.doesNotMatch(nativeResize, /WM_SIZE\s*=>|WM_SIZING\s*=>/)

assert.doesNotMatch(nativeResize, /SetWindowRgn/)

console.log('Stable Desktop-only compositor without per-resize layer toggles: PASS')
console.log('Adaptive hero without abrupt 1040px direction breakpoint: PASS')
console.log('Native WebView2 background synchronization: PASS')
console.log('Transparent Pet/Canvas window protection: PASS')
console.log('DPI-aware full-client non-client frame and native resize zones: PASS')
console.log('Desktop live-resize regression: PASS')
